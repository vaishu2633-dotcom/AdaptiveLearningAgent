/**
 * Helper to fetch mock topic by ID or fallback to Probability (showcase)
 */
export function getMockTopicById(topicId: string): LearningTopic {
  // Check exact ID match
  const found = MOCK_TOPICS.find((t) => t.id === topicId);
  if (found) return found;

  // Check alias mappings (e.g. ds-5 -> ds-stats, ds-6 -> ds-probability, ds-1 -> ds-python)
  const aliasMap: Record<string, string> = {
    'ds-1': 'ds-python',
    'ds-2': 'ds-python',
    'ds-3': 'ds-sql',
    'ds-4': 'ds-python',
    'ds-5': 'ds-stats',
    'ds-6': 'ds-probability',
    'ds-7': 'ds-ml-basics',
    'ds-8': 'ds-regression',
    'ds-9': 'ds-classification',
    'ai-1': 'ai-python',
    'ai-2': 'ai-python',
    'ai-3': 'ai-linalg',
    'ai-4': 'ai-ml',
    'ai-5': 'ai-nn',
    'ai-6': 'ai-dl',
    'ai-7': 'ai-transformers',
    'ai-8': 'ai-genai',
    'ai-9': 'ai-rag',
    'probability': 'ds-probability',
  };

  const mappedId = aliasMap[topicId];
  if (mappedId) {
    const mapped = MOCK_TOPICS.find((t) => t.id === mappedId);
    if (mapped) return mapped;
  }

  // Default fallback: Probability (the central showcase topic)
  return MOCK_TOPICS.find((t) => t.id === 'ds-probability') || MOCK_TOPICS[0];
}
